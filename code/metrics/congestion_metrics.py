import os
import xml.etree.ElementTree as ET
import numpy as np


def parse_and_compute_congestion_e2(
    e2_xml_path,
    incident_start_s,
    incident_end_s,
    streets_zones=dict[str, list[str]],
    congested_queue_threshold_m=20.0,
    baseline_speed_ratio=0.90
):

    summary_congestion_per_zone = {}
    timeseries_records_per_zone = {}
    
    for zone, street_ids in streets_zones.items():
        interval_data = parse_e2_intervals(e2_xml_path, street_ids, congested_queue_threshold_m)
        summary_congestion, timeseries_records = compute_congestion_metrics(interval_data, incident_start_s, incident_end_s, baseline_speed_ratio)
        summary_congestion_per_zone[zone] = summary_congestion
        timeseries_records_per_zone[zone] = timeseries_records

    return summary_congestion_per_zone, timeseries_records_per_zone




def parse_e2_intervals(e2_xml_path, street_ids, congested_queue_threshold_m=20.0):
    if not os.path.exists(e2_xml_path):
        raise FileNotFoundError(f"File not found: {e2_xml_path}")


    # Map intervals: interval_midpoint -> list of detector metrics
    interval_data = {}

    context = ET.iterparse(e2_xml_path, events=("end",))

    for event, elem in context:
        if elem.tag == "interval":
            det_id = elem.get("id")

            ## Check if the detector ID corresponds to any of the street IDs in the zone
            ## Detector has the format "detector_<street_id>_<index>", so we check if any street_id is a substring of det_id
            current_street_id = det_id.split("_")[1] if "_" in det_id else None
            if current_street_id not in street_ids:
                elem.clear()
                continue

            begin = float(elem.get("begin"))
            end = float(elem.get("end"))
            midpoint = (begin + end) / 2.0

            # Native E2 measurements generated by SUMO.
            vehicles_seen = int(elem.get("nVehSeen", 0))
            if vehicles_seen == 0:
                elem.clear()
                continue

            mean_speed = float(elem.get("meanSpeed", 0.0))
            mean_queue = float(elem.get("meanMaxJamLengthInMeters", 0.0))
            max_queue = float(elem.get("maxJamLengthInMeters", 0.0))
            occupancy = float(elem.get("meanOccupancy", 0.0))
            halting = int(elem.get("startedHalts", 0))

            if midpoint not in interval_data:
                interval_data[midpoint] = {
                    "begin": begin,
                    "end": end,
                    "speeds": [],
                    "mean_queues": [],
                    "max_queues": [],
                    "occupancies": [],
                    "halting": 0,
                    "congested_segments": 0
                }

            interval_data[midpoint]["speeds"].append(mean_speed)
            interval_data[midpoint]["mean_queues"].append(mean_queue)
            interval_data[midpoint]["max_queues"].append(max_queue)
            interval_data[midpoint]["occupancies"].append(occupancy)
            interval_data[midpoint]["halting"] += halting

            if mean_queue >= congested_queue_threshold_m:
                interval_data[midpoint]["congested_segments"] += 1

            elem.clear()

    del context

    # Sort the intervals
    sorted_midpoints = sorted(interval_data.keys())
    sorted_interval_data = {midpoint: interval_data[midpoint] for midpoint in sorted_midpoints}

    return sorted_interval_data

def compute_congestion_metrics(interval_data, incident_start_s, incident_end_s, baseline_speed_ratio=0.90):
    # Aggregators for summary
    pre_incident_speeds = []
    incident_mean_queues = []
    incident_max_queues = []
    incident_congested_counts = []
    
    recovery_time_s = None
    baseline_speed = None
    timeseries_records = []

    for midpoint, data in interval_data.items():
        avg_speed = float(np.mean(data["speeds"])) if data["speeds"] else 0.0
        avg_queue = float(np.mean(data["mean_queues"])) if data["mean_queues"] else 0.0
        peak_queue = float(np.max(data["max_queues"])) if data["max_queues"] else 0.0
        congested_count = data["congested_segments"]

        incident_mean_queues.append(avg_queue)
        incident_max_queues.append(peak_queue)
        incident_congested_counts.append(congested_count)

        if midpoint < incident_start_s:
            if data["speeds"]:
                pre_incident_speeds.append(avg_speed)

        else:
            if baseline_speed is None:
                baseline_speed = float(np.mean(pre_incident_speeds)) if pre_incident_speeds else 10.0
            
            # Check recovery condition
            if recovery_time_s is None and avg_speed >= (baseline_speed * baseline_speed_ratio):
                recovery_time_s = round(midpoint - incident_end_s, 2)

        timeseries_records.append({
            "time_begin_s": data["begin"],
            "time_end_s": data["end"],
            "interval_midpoint_s": midpoint,
            "mean_speed_mps": round(avg_speed, 3),
            "mean_queue_length_m": round(avg_queue, 2),
            "max_queue_length_m": round(peak_queue, 2),
            "halting_vehicles_total": data["halting"],
            "congested_segments_count": congested_count
        })

    summary_congestion = {
        "mean_queue_length_m": round(float(np.mean(incident_mean_queues)), 2) if incident_mean_queues else 0.0,
        "max_queue_length_m": round(float(np.max(incident_max_queues)), 2) if incident_max_queues else 0.0,
        "mean_congested_segments": round(float(np.mean(incident_congested_counts)), 2) if incident_congested_counts else 0.0,
        "max_congested_segments": int(np.max(incident_congested_counts)) if incident_congested_counts else 0,
        "network_recovery_time_s": recovery_time_s if recovery_time_s is not None else -1.0
    }

    return summary_congestion, timeseries_records